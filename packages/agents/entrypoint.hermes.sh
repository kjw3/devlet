#!/bin/bash
# devlet/agent-hermes entrypoint
# Configures Hermes (Nous Research) from devlet env vars and starts `hermes chat`.
#
# Configuration is managed by /usr/local/lib/hermes-config.mjs which:
#   - Merges a versioned baseline with existing settings and explicit overrides
#   - Preserves user-modified settings across restarts
#   - Uses atomic writes with 0600 permissions
#   - Never overwrites a valid config on parse failure
set -e

. /usr/local/bin/devlet-terminal
. /usr/local/bin/devlet-ssh
. /usr/local/bin/devlet-tailscale
. /usr/local/bin/devlet-coding-init
. /usr/local/bin/devlet-services

AGENT_NAME="${DEVLET_AGENT_NAME:-Hermes Agent}"
AGENT_ROLE="${DEVLET_AGENT_ROLE:-Autonomous AI agent}"
AGENT_MISSION="${DEVLET_AGENT_MISSION:-}"

# ─── Resolve provider/model ─────────────────────────────────────────────────
# Provider priority: explicit env > native key > LiteLLM.
# The provider/model resolution here only determines what to pass to
# hermes-config.mjs — the actual config writing is done by the JS module.
PROVIDER="${DEVLET_AGENT_PROVIDER:-}"
if [ -z "$PROVIDER" ]; then
  if   [ -n "${ANTHROPIC_API_KEY:-}" ];  then PROVIDER="anthropic"
  elif [ -n "${OPENAI_API_KEY:-}" ];     then PROVIDER="openai"
  elif [ -n "${OPENROUTER_API_KEY:-}" ]; then PROVIDER="openrouter"
  elif [ -n "${GEMINI_API_KEY:-}" ];     then PROVIDER="gemini"
  elif [ -n "${NVIDIA_API_KEY:-}" ];     then PROVIDER="nvidia"
  elif [ -n "${GROQ_API_KEY:-}" ];       then PROVIDER="groq"
  elif [ -n "${LITELLM_BASE_URL:-}" ] && [ -n "${LITELLM_API_KEY:-}" ]; then PROVIDER="litellm"
  else PROVIDER="anthropic"; fi
fi

MODEL="${DEVLET_AGENT_MODEL:-}"
# On LiteLLM, choose a model that the proxy actually serves.
if [ -z "$MODEL" ] && [ "$PROVIDER" = "litellm" ]; then
  MODEL=$(_dci_litellm_model hermes)
fi
MODEL="${MODEL:-claude-sonnet-4-6}"

export DEVLET_AGENT_PROVIDER="$PROVIDER"
export DEVLET_AGENT_MODEL="$MODEL"
echo "[devlet] hermes agent=\"$AGENT_NAME\" provider=$PROVIDER model=$MODEL"

# ─── Generate config.yaml and .env via Node.js module ──────────────────────
# The module reads HERMES_HOME, DEVLET_AGENT_PROVIDER, DEVLET_AGENT_MODEL,
# and any HERMES_* tuning env vars. It handles:
#   - Merge policy (baseline < existing < overrides)
#   - Atomic writes with 0600 permissions
#   - .env preservation (unmanaged entries survive)
#   - Error safety (never overwrites valid config on parse failure)
#
# For LiteLLM, pass the pre-resolved model via env to avoid shell interpolation
# of model names that may contain special characters.
HERMES_LITELLM_MODEL="$MODEL" node "${HERMES_CONFIG_MODULE:-/usr/local/lib/hermes-config/index.mjs}"

# ─── Generate mission files via Node ───────────────────────────────────────
node - <<'JSEOF'
const fs   = require('fs');
const name     = process.env.DEVLET_AGENT_NAME     || 'Hermes Agent';
const role     = process.env.DEVLET_AGENT_ROLE     || 'Autonomous AI agent';
const mission  = process.env.DEVLET_AGENT_MISSION  || '';

const missionBlock = mission
  ? `## Primary Mission\n${mission}\n\n## Conduct\n- Execute the mission autonomously.\n- Report blockers clearly.\n- Summarize what was done when complete.`
  : '## Status\n\nNo mission assigned. Await instructions from the operator.';

fs.mkdirSync('/workspace', { recursive: true });
fs.writeFileSync('/workspace/AGENTS.md', [
  '# Agent Instructions', '',
  `You are **${name}** — ${role}`, '',
  missionBlock, '',
  '_Generated by Devlet._',
].join('\n'));

console.log('[devlet] /workspace/AGENTS.md written');
JSEOF

# ─── Run headless (single mission) or interactive ──────────────────────────
if [ -n "$AGENT_MISSION" ]; then
  echo "[devlet] hermes: headless mission mode"
  exec hermes chat --yolo --mission "$AGENT_MISSION"
else
  echo "[devlet] hermes: interactive mode"
  exec hermes chat
fi
